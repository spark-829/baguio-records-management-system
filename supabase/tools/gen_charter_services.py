#!/usr/bin/env python3
"""Generate the rms_services data migration from the Citizen's Charter catalog.

Usage:
  python3 -I supabase/tools/gen_charter_services.py supabase/tools/charter-services.json \
    > supabase/migrations/20261125000400_rms_charter_services_data.sql

Stdlib only. Exits 1 (message on stderr) when a check fails.
"""
import json
import re
import sys

KEYS = ["classification", "confidential", "division", "fee_php", "fee_text", "no", "office",
        "steps", "title", "total_minutes", "total_text", "tx", "who"]
CLASS = {"Simple": "simple", "Complex": "complex", "Highly Technical": "highly_technical"}
TX_OK = {"G2C", "G2G", "G2B"}
NAME_RE = re.compile(r"\b(Engr|Atty|Dr|Mr|Mrs|Ms|Hon|Arch)\.|\b[A-Z]\.\s?[A-Z][a-z]+")


def fail(msg):
    sys.stderr.write("error: " + msg + "\n")
    sys.exit(1)


def doc_type(title):
    if re.search(r"complaint", title, re.I):
        return "Complaint"
    if re.search(r"voucher", title, re.I):
        return "Disbursement Voucher"
    if re.search(r"request|application|issuance|registration|permit|certif|clearance|license|licence|petition|inquiry|assistance|reservation", title, re.I):
        return "Request / Complaint"
    return "Letter"


def q(v):
    if v is None:
        return "null"
    return "'" + str(v).replace("'", "''") + "'"


def num(v):
    return "null" if v is None else repr(v) if isinstance(v, float) else str(int(v))


def main():
    if len(sys.argv) != 2:
        fail("usage: gen_charter_services.py services.json")
    with open(sys.argv[1], encoding="utf-8") as fh:
        data = json.load(fh)
    if len(data) != 228:
        fail("expected 228 services, found %d" % len(data))
    seen = set()
    pos = {}
    rows = []
    for s in data:
        missing = [k for k in KEYS if k not in s]
        if missing:
            fail("service %s/%s is missing keys %s" % (s.get("office"), s.get("no"), missing))
        key = (s["office"], str(s["no"]))
        if key in seen:
            fail("duplicate service %s/%s" % key)
        seen.add(key)
        if s["classification"] not in CLASS:
            fail("unknown classification %r for %s/%s" % (s["classification"], *key))
        tx = []
        for t in s["tx"]:
            if t not in TX_OK:
                fail("unknown tx %r for %s/%s" % (t, *key))
            if t not in tx:
                tx.append(t)
        if not tx:
            fail("no tx for %s/%s" % key)
        steps = []
        for i, st in enumerate(s["steps"], 1):
            for field in (st.get("by"), st.get("action")):
                if field and NAME_RE.search(field):
                    fail("personal name in a step of %s/%s: %r" % (key + (field,)))
            m = st.get("minutes")
            steps.append({"n": i, "action": st.get("action"), "by": st.get("by"), "minutes": None if m is None else int(m)})
        if s["who"] and NAME_RE.search(s["who"]):
            fail("personal name in who of %s/%s: %r" % (key + (s["who"],)))
        pos[s["office"]] = pos.get(s["office"], 0) + 1
        rows.append((s, tx, steps, pos[s["office"]]))

    out = []
    out.append("-- Baguio RMS: Citizen's Charter services (228 rows). GENERATED by supabase/tools/gen_charter_services.py from")
    out.append("-- supabase/tools/charter-services.json. Do not edit by hand; change the JSON and generate again.")
    out.append("-- Run after 20261125000300. Safe to run again (rows that did not change are skipped). No drops or deletes.")
    out.append("")
    cols = ["service_no", "title", "division", "who", "classification", "tx_types", "fee_text", "fee_php",
            "total_minutes", "total_text", "confidential", "doc_type_name", "steps", "sort_order"]
    out.append("insert into public.rms_services (office_id, " + ", ".join(cols) + ")")
    out.append("select o.id, " + ", ".join("v." + c for c in cols))
    out.append("from (values")
    vals = []
    for s, tx, steps, p in rows:
        txs = "array[" + ", ".join(q(t) for t in tx) + "]::text[]"
        stj = q(json.dumps(steps, ensure_ascii=False, separators=(",", ":"))) + "::jsonb"
        vals.append("  (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %d)" % (
            q(s["office"]), q(str(s["no"])), q(s["title"]), q(s["division"]), q(s["who"]), q(CLASS[s["classification"]]),
            txs, q(s["fee_text"]), num(s["fee_php"]) + ("::numeric" if s["fee_php"] is not None else "::numeric"),
            num(s["total_minutes"]) + "::int", q(s["total_text"]), "true" if s["confidential"] else "false",
            q(doc_type(s["title"])), stj, p))
    out.append(",\n".join(vals))
    out.append(") v(code, " + ", ".join(cols) + ")")
    out.append("join public.rms_offices o on o.code = v.code")
    out.append("on conflict (office_id, service_no) do update set")
    out.append("  " + ",\n  ".join("%s = excluded.%s" % (c, c) for c in cols if c != "service_no") + ",")
    out.append("  updated_at = now()")
    tup = lambda p: "(" + ", ".join(p + c for c in cols if c != "service_no") + ")"
    out.append("where " + tup("public.rms_services.") + " is distinct from " + tup("excluded.") + ";")
    out.append("")
    out.append("notify pgrst, 'reload schema';")
    sys.stdout.write("\n".join(out) + "\n")


main()
